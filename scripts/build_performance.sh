## Method

Each `pilot_mp <op>` invocation draws **one fresh random operand** (seeded
from the OS clock and the process id, so every trial is independent) and
measures it as follows: the operation is repeated, doubling the count, until
one batch lasts at least the 2 ms calibration floor, and the reading is the
batch's elapsed time divided by its repetition count. The floor is chosen so
that timer resolution and loop overhead are negligible against the reading.
pilot-bench runs the program repeatedly until the mean's 95 % confidence
interval converges or the session budget runs out; the saved readings are then
a random sample of the primitive's cost over random inputs, reduced by
`scripts/bench_primitives.sh` into:

- the **mean** — the sample mean of every reading, the average cost over
  random inputs — with its 95 % confidence interval and the reading count
  `n`; and
- the **extrema** — min / p50 / p99 / max and the `max/min` spread, which for
  a variable-time primitive is the data-dependent behaviour that a mean hides.

Two primitives are **heavy-tailed**, and their session budget is four times the
others' (120 s against 30 s). `is_probable_prime` on a random operand is a
mixture: even operands are caught by the first prime of the trial-division
sieve, and most odd composites by one of its 168 primes below 1000, at the cost
of a linear pass per prime. Only about one odd operand in six survives the
sieve (Mertens: ∏(1 − 1/p) over odd primes below 1000 is about 0.16), and each
survivor pays at least one full Miller–Rabin exponentiation; a prime, at
probability 1/ln 2ⁿ, pays all twelve rounds. The mean is well defined, but the
tail sets it, so a faithful estimate needs a sample of several hundred
readings. `mod_sqrt` has the same structure: a non-residue is rejected by one
Jacobi symbol, a residue modulo a prime `p ≡ 3 (mod 4)` takes a single
exponentiation, and a residue modulo `p ≡ 1 (mod 4)` pays the Tonelli–Shanks
descent, or Cipolla's algorithm once the descent would be deeper than a
threshold set by the modulus width. Each `mod_sqrt` trial must also generate a
fresh random prime modulus, and at the wide sizes that generation costs far
more than the operation timed, so the session ends with few readings; the
reading count `n` and the confidence-interval column disclose this per cell.

Two marks follow from this. A mean whose confidence interval never tightened
below 10 % of the mean within the session is printed with a leading `~`: it is
the whole-sample mean and stands, but the extrema are the primary result. A
cell with fewer than thirty readings prints `insufficient-sample(n=…)` in place
of a mean, because the mean of a few draws from a bimodal cost is one coin flip
between the populations, not a measurement; its order statistics stay.
`scripts/check_bench_consistency.py` enforces the arithmetic invariant that
ties the columns together: from the reading count and the quantile positions
it bounds the whole-sample mean above and below, and a mean outside those
bounds cannot have come from the sample its own quantiles describe. The build
runs that check first and refuses to proceed if any row fails it.

The prime-conditioned rows (`isprime_true`, `sqrtmod_blum`, `sqrtmod_descent`)
carry the same structural limit as `mod_sqrt`: every trial first generates a
random prime of the row's width, which bounds the session's reading count at
the widest sizes. Their costs are otherwise tight: `isprime_true` is the sieve
plus exactly twelve Miller–Rabin rounds, and the two `sqrtmod_*` rows each pin
one engine of `mod_sqrt`. The mixture rows characterize the distribution a
random operand induces; the conditioned rows give the cost a caller plans
around.

Operation glossary (integer sizes are the operand bit width; field sizes are the
degree of GF(2^m)):

| op | what it measures |
|---|---|
| `add` `sub` | one carry or borrow pass over two random operands, into caller-held storage (`add_into` / `sub_into`) |
| `mul` `sqr` | a full product or square of random operands |
| `divrem` `rem` | Knuth Algorithm D division, full width by half width |
| `modmul` | one `mul` then a reduction, general (non-Montgomery) modulus |
| `barrettmul` | `BarrettContext::mod_mul` with the context prepared once and the operands already reduced, as in an exponentiation loop — the reuse counterpart of `modmul` |
| `barrettsetup` | building a `BarrettContext` (the one division for μ) |
| `montmul` `montsqr` | one Montgomery multiply / square, operands already in the domain, fresh scratch per call |
| `montmul_scratch` `montsqr_scratch` | the same with one `MontgomeryScratch` kept across calls — the difference is the per-call scratch allocation |
| `montsetup` | building a `MontgomeryContext` (the one division and R² setup) |
| `gcd` `gcdext` `modinv` `jacobi` | the number-theory family |
| `sqrtmod` | `mod_sqrt` on a random operand and a random prime — the outcome mixture |
| `sqrtmod_blum` | `mod_sqrt` on a guaranteed residue, prime pinned to `p ≡ 3 (mod 4)` — the `(p+1)/4` shortcut, isolated |
| `sqrtmod_descent` | `mod_sqrt` on a guaranteed residue, prime pinned to `p ≡ 1 (mod 4)` — the Tonelli–Shanks descent, isolated |
| `isprime` | `is_probable_prime` on a fully random operand — the outcome mixture; its extrema carry the variable-time signal |
| `isprime_true` | `is_probable_prime` on a random prime of the row's width — the accept cost: the sieve plus all twelve Miller–Rabin rounds |
| `gf2m_*` | binary-field multiply / square / sqrt / pow / inverse over the two FIPS 186-4 fields B-233 and B-571 |

Three rows measure exponentiation under fixed workloads taken from classical
public-key cryptography. rump is a general-purpose multiprecision library;
these rows exist for the measurement axes they pin down.

| op | workload | what it isolates |
|---|---|---|
| `montpow_e65537` | RSA verification: exponent fixed at 65537 | the exponent floor — kernel scaling with exponent work at its minimum |
| `montpow_rand` | finite-field DH/DSA: fresh random exponent of fixed 256-bit length | the realistic-exponent axis at constant length, so the size fit varies one variable |
| `modpow` | the same DH-shaped workload through the public `mod_pow` | dispatch overhead relative to `montpow_rand` (the modulus is odd, so `mod_pow` runs the Montgomery path) |

Exponentiation cost is (exponent bits) × (kernel cost) and is linear in
exponent length, so the cost at any other exponent length follows from these
rows by proportion.

