### Interpretation

The ratios sort by **algorithm**, not by language, and the tables above are
read against that grouping:

- **Matched algorithm; the gap is the inner loop.** `modpow` runs windowed
  exponentiation on both sides, and `mul`, `sqr`, `divrem`, and `modmul`
  run rump's schoolbook-range kernels at every size in the table. What
  separates the columns there is GMP's assembly inner loops against rump's
  portable Rust; the ratio is a constant factor of the kernel, not a
  difference of algorithm.

- **`add` and `sub`.** Both pilots write the result into long-lived storage
  (`mpz_add(r, a, b)` into a reused `r`; rump's `add_into` / `sub_into`
  into a reused buffer), so the comparison is one carry chain against
  another. At 256 bits call overhead is a large share of both sides, so the
  narrowest row measures overhead as much as the carry chain; the wider rows
  measure the chains themselves.

- **The Euclid family.** At these sizes rump runs Lehmer's algorithm under
  `gcd`, `gcdext`, and `modinv`, and the Lehmer-batched symbol state under
  `jacobi`, all four quadratic. The ratios in those rows therefore compare
  Lehmer's batching against GMP's inner loops at the sizes where rump has
  not yet changed algorithm; rump's Half-GCD engines enter above this
  table's range, and *GCD at scale* measures the family where they do and
  where the two libraries run the same subquadratic algorithm.

- **Why the ratios differ by host.** The assembly edge is not the same on
  every core, because how far hand-scheduled assembly outruns compiled Rust
  depends on the pipeline it runs on. The same operation therefore shows a
  different ratio on each host, and the four tables are four measurements
  of the same code against four assembly targets, not four opinions about
  the algorithm.

## NTT and the ladder

rump's multiplication ladder is schoolbook, Karatsuba from 96 limbs, Toom-3
from 128, Toom-4 from 4096, and an exact number-theoretic transform from
131,072 limbs on one execution context, or from 8192 limbs when four or more
execution contexts are available to it. Squaring has its own schoolbook kernel
from 8 limbs and Karatsuba squaring to 1024 limbs, then the multiplication
ladder.

No table in this document measures any of those upper rungs. The primitives
tables stop at 64 limbs, below the first Karatsuba split, and the gcd sweep
below tops out at 16,384 limbs, below the single-context NTT threshold, so
its matrix products stay on the Toom rungs and below. The crossovers themselves are
set by the ignored timing probes in the crate's test suite, one per rung
(`karatsuba_crossover_timing`, `toom_crossover_timing`,
`squaring_crossover_timing`, `ntt_crossover_timing`, and the gcd-family
`hgcd_crossover_timing`, `hgcd_ext_crossover_timing`,
`jacobi_hgcd_crossover_timing`); each prints its own comparison when run with

```sh
cargo test --release --lib <probe_name> -- --ignored --nocapture
```

and their output is not reproduced here.

## GCD at scale

The tables above stop at 64 limbs, where the whole family runs its Lehmer
engine. This section sweeps the family from 8 kbit to 1 Mbit (128 to 16,384
limbs) on the EPYC, against GMP on the same host, and every one of the four
changes algorithm inside that range. `gcd` dispatches to Half-GCD at 2048 limbs
(Möller, *On Schönhage's algorithm and subquadratic integer gcd computation*,
Math. Comp. 77 (2008)), computing the reduction matrix from the operands' top
halves by recursion and replacing Lehmer's O(n²) with O(M(n)·log n).
`gcd_extended` and `mod_inverse` ride the same driver with the transform
accumulated, and their crossover is lower, at 512 limbs, because Lehmer's
extended form carries full-width signed cofactors through every batch while
the driver folds that work into one matrix accumulation per round. `jacobi`
threads its symbol state through the Half-GCD recursion from 2048 limbs, the
same crossover as `gcd`'s: every quotient the recursion applies materializes
in a Lehmer batch or a guarded division, and the state consumes each one, so
the symbol is O(M(n)·log n) end to end.

How to read the fit table below: each rump exponent is a fit across both
regimes, since the sweep's lower rows still run Lehmer and the subquadratic
engine begins only at the dispatch size, so the exponents understate the bend
in the upper rows. The GMP column is the reference the rump column is read
against: above the crossovers both libraries run Half-GCD, and what separates
the columns there is no longer the algorithm but its constants: the
multiplication ladder underneath the matrix work, and GMP's assembly inner
loops.

