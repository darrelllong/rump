## Fitted complexity

Least-squares log–log fit of mean against bit width, `mean ≈ c·n^α`, over the
four primitives sizes; the table gives the **exponent α** only. The fit's
intercept `c` is deliberately not shown: it carries units of ns/bit^α, not
nanoseconds, so it is neither a time nor comparable across rows with different
α. Read actual times from the cost tables below, never α or `c` as a speed.

The primitives sizes span 4 to 64 limbs, and at those widths the exponents are
**sub-asymptotic**: fixed per-call overhead is a large share of every reading,
so expect a linear carry pass (`add`, `sub`) to fit below α = 1 and the
quadratic kernels (`mul`, `divrem`, `montmul`) below α = 2, the flattening
strongest on the cheapest rows. A higher α means a steeper curve, not a slower
operation. The
Complexity column is the label `perf_analysis.py` attaches to each method; the
kernels the sizes fall in are given under each family in *Cost by method*.
`sqrtmod` and `isprime` are heavy-tailed: their mean is set by a rare
expensive population, so a finite sample estimates it loosely and their fitted
exponent is unreliable — read their extrema instead.

