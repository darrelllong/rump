## Extrema — the variable-time signal

Ranked by `max/min` spread on the M4, over the primitives sizes and the
extended heavy-tail record. A spread near 1.0 is data-independent; a large
spread means the primitive's cost depends on its input, which is why rump is
explicitly variable-time and must not be used where timing may not leak
secrets.

Two operations produce the large spreads, and both are **mixtures** whose
populations the conditioned rows separate:

- **`isprime`** mixes a sieve rejection, overwhelmingly likely on a random
  operand, with a full twelve-round Miller–Rabin pass on a prime;
  `isprime_true` isolates the prime outcome.
- **`mod_sqrt`** mixes three populations. Half of all inputs are non-residues
  and exit at the Jacobi symbol — the row's minimum. Residues split again by
  the prime's 2-adic structure: `p ≡ 3 (mod 4)` takes the `(p+1)/4` shortcut
  (`sqrtmod_blum`), and `p ≡ 1 (mod 4)` pays the Tonelli–Shanks descent
  (`sqrtmod_descent`), whose cost grows with the square of `s = v₂(p−1)`.
  `s` is geometric — `P(s = k | p ≡ 1 mod 4) = 2^(1−k)` — so the descent's
  tail is rare and unbounded, and past a depth set by the modulus width the
  dispatch hands the root to Cipolla's algorithm, whose cost is flat in `s`,
  which caps the tail at the crossover cost.

**The mixture rows' medians must not be compared across sizes.** The
non-residue population holds exactly half of `mod_sqrt`'s probability mass, so
its per-cell median is an order statistic sitting on a cluster boundary — a
fair coin between the rejection cost and the extraction cost — and can land on
either population from one session to the next. Each landing point is a
genuine population cost; which population owns the median is the coin. Read
the conditioned rows for costs, the mixture rows for extrema.

Every other row — plain arithmetic, the Montgomery kernels, the Euclid family,
GF(2^m) — has a spread near 1.0: cost tracks operand width, which is public,
not the operand values. The sentence after the table is generated from those
rows and states their range.

